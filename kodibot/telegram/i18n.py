def t(key: str, **kwargs) -> str:
    value = TEXT.get(LANG, TEXT["en"]).get(key, TEXT["en"].get(key, key))
    return value.format(**kwargs) if kwargs else value


def repeat_mode_label(mode: str) -> str:
    return t(f"repeat_{mode}") if mode in {"off", "one", "all"} else mode


def store_message(message: str) -> str:
    if not message:
        return message
    exact = {
        "Playlist directory is not available.": t("playlist_dir_unavailable"),
        "Queue empty.": t("queue_empty"),
        "Playlist file not found.": t("playlist_file_not_found"),
        "Invalid playlist format.": t("invalid_playlist_format"),
        "Invalid index.": t("invalid_index"),
        "You cannot delete the currently playing title. Use /skip or /stop first.": t("cannot_delete_playing"),
    }
    if message in exact:
        return exact[message]
    for prefix, key in (
        ("Save failed: ", "save_failed"),
        ("Load failed: ", "load_failed"),
        ("Delete failed: ", "delete_failed"),
    ):
        if message.startswith(prefix):
            return t(key, error=message[len(prefix):])
    return message


def state_label(value: str) -> str:
    key = str(value or "unknown").strip().lower()
    if key in {"on", "off", "unknown"}:
        return t(f"state_{key}")
    return value


def localized_asset(filename_en: str, filename_de: str) -> str:
    filename = filename_de if LANG == "de" else filename_en
    return os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
        "assets",
        filename,
    )
